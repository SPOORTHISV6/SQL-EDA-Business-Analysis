SELECT
    p.category,
    SUM(s.sales_amount) AS total_sales
FROM fact_sales s
JOIN dim_products p
    ON s.product_key = p.product_key
GROUP BY p.category
ORDER BY total_sales DESC;



SELECT
    p.product_name,
    SUM(s.sales_amount) AS total_sales,
    RANK() OVER (
        ORDER BY SUM(s.sales_amount) DESC
    ) AS sales_rank
FROM fact_sales s
JOIN dim_products p
    ON s.product_key = p.product_key
GROUP BY p.product_name;
