SELECT
	C.CUSTOMER_KEY,
    C.FIRST_NAME,
    C.LAST_NAME,
    SUM(F.SALES_AMOUNT) AS TOTAL_REVENUE
FROM
DIM_CUSTOMERS AS C
LEFT JOIN 
FACT_SALES AS F
ON C.CUSTOMER_KEY = F.CUSTOMER_KEY
GROUP BY 
	C.CUSTOMER_KEY,
    C.FIRST_NAME,
    C.LAST_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

